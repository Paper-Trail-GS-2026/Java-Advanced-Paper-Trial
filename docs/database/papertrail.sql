        SAVEPOINT test_attempt;
        BEGIN
            EXECUTE IMMEDIATE p_sql;
        EXCEPTION WHEN OTHERS THEN
            v_actual := SQLCODE;
        END;
        ROLLBACK TO test_attempt;
        IF v_actual <> p_code THEN
            RAISE_APPLICATION_ERROR(-20991, p_label || ': expected error ' || p_code || ', received ' || v_actual);
        END IF;
    END;
