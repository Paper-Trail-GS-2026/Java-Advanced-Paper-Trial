PROMPT 06. PKG_PREPARATION: specification and body

-- Errors: -20002 invalid ID; -20003 preparation not found;
-- -20004 invalid owner; -20005 invalid service; -20006 invalid version;
-- -20007 invalid title. The installer uses -20001 for existing names.
-- Check JWT ownership and the Java snapshot in the API before calling this package.
CREATE OR REPLACE PACKAGE PKG_PREPARATION AUTHID DEFINER AS
    FUNCTION completion_percentage(
        p_preparation_id IN PT_PREPARATION.ID%TYPE
    ) RETURN NUMBER;

    PROCEDURE create_preparation(
        p_owner_subject IN PT_PREPARATION.OWNER_SUBJECT%TYPE,
        p_service_id IN PT_PREPARATION.SERVICE_ID%TYPE,
        p_source_version IN PT_PREPARATION.SOURCE_VERSION%TYPE,
        p_title IN PT_PREPARATION.TITLE%TYPE,
        p_id OUT PT_PREPARATION.ID%TYPE
    );
END PKG_PREPARATION;
/

CREATE OR REPLACE PACKAGE BODY PKG_PREPARATION AS
    c_max_integer CONSTANT NUMBER := 999999999999999999;

    FUNCTION completion_percentage(
        p_preparation_id IN PT_PREPARATION.ID%TYPE
    ) RETURN NUMBER IS
        v_required NUMBER;
        v_completed NUMBER;
    BEGIN
        IF p_preparation_id IS NULL OR p_preparation_id <= 0
            OR p_preparation_id > c_max_integer OR p_preparation_id <> TRUNC(p_preparation_id) THEN
            RAISE_APPLICATION_ERROR(-20002, 'Preparation ID must be a positive integer with at most 18 digits.');
        END IF;

        -- LEFT JOIN keeps preparations that have no items.
        SELECT COUNT(CASE WHEN i.REQUIRED = 1 THEN 1 END),
               COUNT(CASE WHEN i.REQUIRED = 1 AND i.COMPLETED = 1 THEN 1 END)
        INTO v_required, v_completed
        FROM PT_PREPARATION p
        LEFT JOIN PT_PREPARATION_ITEM i ON i.PREPARATION_ID = p.ID
        WHERE p.ID = p_preparation_id
        GROUP BY p.ID;

        IF v_required = 0 THEN
            RETURN 0;
        END IF;
        RETURN 100 * v_completed / v_required;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20003, 'Preparation not found.');
    END completion_percentage;

    PROCEDURE create_preparation(
        p_owner_subject IN PT_PREPARATION.OWNER_SUBJECT%TYPE,
        p_service_id IN PT_PREPARATION.SERVICE_ID%TYPE,
        p_source_version IN PT_PREPARATION.SOURCE_VERSION%TYPE,
        p_title IN PT_PREPARATION.TITLE%TYPE,
        p_id OUT PT_PREPARATION.ID%TYPE
    ) IS
    BEGIN
        IF p_owner_subject IS NULL OR LENGTH(p_owner_subject) > 128
            OR NOT REGEXP_LIKE(p_owner_subject, '[^[:space:]]') THEN
            RAISE_APPLICATION_ERROR(-20004, 'Owner is required, must not be blank and must have at most 128 characters.');
        END IF;
        IF p_service_id IS NULL OR p_service_id <= 0
            OR p_service_id > c_max_integer OR p_service_id <> TRUNC(p_service_id) THEN
            RAISE_APPLICATION_ERROR(-20005, 'Service ID must be a positive integer with at most 18 digits.');
        END IF;
        IF p_source_version IS NULL OR p_source_version <= 0
            OR p_source_version > c_max_integer OR p_source_version <> TRUNC(p_source_version) THEN
            RAISE_APPLICATION_ERROR(-20006, 'Version must be a positive integer with at most 18 digits.');
        END IF;
        IF p_title IS NULL OR LENGTH(p_title) > 160
            OR NOT REGEXP_LIKE(p_title, '[^[:space:]]') THEN
            RAISE_APPLICATION_ERROR(-20007, 'Title is required, must not be blank and must have at most 160 characters.');
        END IF;

        -- Insert the snapshot items before committing this preparation.
        INSERT INTO PT_PREPARATION (OWNER_SUBJECT, SERVICE_ID, SOURCE_VERSION, TITLE)
        VALUES (p_owner_subject, p_service_id, p_source_version, p_title)
        RETURNING ID INTO p_id;
    END create_preparation;
END PKG_PREPARATION;
