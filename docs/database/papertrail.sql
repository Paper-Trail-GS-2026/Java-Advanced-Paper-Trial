PROMPT 01. Check existing objects
SELECT SYS_CONTEXT('USERENV', 'DB_NAME') AS DATABASE_NAME,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS SCHEMA_NAME FROM DUAL;

DECLARE
    v_objects NUMBER;
    v_constraints NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_objects FROM USER_OBJECTS
    WHERE SUBSTR(OBJECT_NAME, 1, 3) = 'PT_'
       OR SUBSTR(OBJECT_NAME, 1, 6) = 'IX_PT_'
       OR OBJECT_NAME = 'PKG_PREPARATION';
    SELECT COUNT(*) INTO v_constraints FROM USER_CONSTRAINTS
    WHERE SUBSTR(CONSTRAINT_NAME, 1, 6) IN ('PK_PT_', 'UQ_PT_', 'CK_PT_', 'FK_PT_');
    IF v_objects + v_constraints > 0 THEN
        RAISE_APPLICATION_ERROR(-20001,
            'Installation stopped: reserved PaperTrail objects or constraints already exist. Do not delete or overwrite automatically.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('PT_ names are available. No existing objects were changed.');
END;
