PROMPT === 05. Testes da base, com rollback das alteracoes de teste ===

DECLARE
    v_count NUMBER;
    v_id NUMBER;
    PROCEDURE assert_count(p_sql VARCHAR2, p_expected NUMBER, p_label VARCHAR2) IS
        v_actual NUMBER;
    BEGIN
        EXECUTE IMMEDIATE p_sql INTO v_actual;
        IF v_actual <> p_expected THEN
            RAISE_APPLICATION_ERROR(-20990, p_label || ': esperado ' || p_expected || ', obtido ' || v_actual);
        END IF;
    END;

    PROCEDURE expect_error(p_sql VARCHAR2, p_code NUMBER, p_label VARCHAR2) IS
        v_actual NUMBER := 0;
    BEGIN
        SAVEPOINT tentativa;
        BEGIN
            EXECUTE IMMEDIATE p_sql;
        EXCEPTION WHEN OTHERS THEN
            v_actual := SQLCODE;
        END;
        ROLLBACK TO tentativa;
        IF v_actual <> p_code THEN
            RAISE_APPLICATION_ERROR(-20991, p_label || ': esperado erro ' || p_code || ', obtido ' || v_actual);
        END IF;
    END;
BEGIN
    assert_count('SELECT COUNT(*) FROM PT_CATEGORIA', 2, 'Categorias');
    assert_count('SELECT COUNT(*) FROM PT_SERVICO', 3, 'Serviços');
    assert_count('SELECT COUNT(*) FROM PT_REQUISITO', 8, 'Requisitos');
    assert_count('SELECT COUNT(*) FROM PT_PREPARATIVO', 7, 'Preparativos');
    assert_count('SELECT COUNT(*) FROM PT_ITEM_PREPARATIVO', 14, 'Itens');
    assert_count('SELECT COUNT(*) FROM PT_VERSAO_SERVICO', 3, 'Versões');
    assert_count('SELECT COUNT(*) FROM PT_ITEM_PREPARATIVO WHERE PREPARATIVO_ID = 107', 0, 'Preparativo vazio');
    assert_count('SELECT COUNT(*) FROM PT_ITEM_PREPARATIVO WHERE PREPARATIVO_ID = 106 AND OBRIGATORIO = 1', 0, 'Somente opcionais');

    expect_error('UPDATE PT_ITEM_PREPARATIVO SET CONCLUIDO = 2 WHERE ID = 101', -2290, 'Estado inválido');
    expect_error('UPDATE PT_ITEM_PREPARATIVO SET OBRIGATORIO = -1 WHERE ID = 101', -2290, 'Obrigatório inválido');
    expect_error(q'[INSERT INTO PT_ITEM_PREPARATIVO (PREPARATIVO_ID, TITULO) VALUES (999, 'Vínculo inexistente')]', -2291, 'Preparativo inexistente');
    expect_error('UPDATE PT_PREPARATIVO SET TITULO = ''   '' WHERE ID = 101', -2290, 'Título em branco');
    expect_error('UPDATE PT_PREPARATIVO SET VERSAO_ORIGEM = 0 WHERE ID = 101', -2290, 'Versão inválida');
    expect_error('DELETE FROM PT_PREPARATIVO WHERE ID = 101', -2292, 'Exclusão sem tratar itens');

    -- IDs externos não exigem que o catálogo esteja no schema do .NET.
    SAVEPOINT referencias_externas;
    INSERT INTO PT_PREPARATIVO (OWNER_SUBJECT, SERVICO_ID, VERSAO_ORIGEM, TITULO)
    VALUES ('fixture-external', 999, 1, 'Referência validada pela aplicação')
    RETURNING ID INTO v_id;
    IF v_id < 1000 THEN
        RAISE_APPLICATION_ERROR(-20993, 'Identity invadiu a faixa das fixtures');
    END IF;
    ROLLBACK TO referencias_externas;

    SAVEPOINT idempotencia;
    INSERT INTO PT_IDEMPOTENCIA (OWNER_SUBJECT, OPERACAO, CHAVE, PAYLOAD_HASH, RESPOSTA_STATUS, RESPOSTA_JSON)
    VALUES ('fixture-citizen-a', 'CREATE_PREPARATION', 'base-test', RPAD('a', 64, 'a'), 201, '{"id":101}');
    expect_error(q'[INSERT INTO PT_IDEMPOTENCIA (OWNER_SUBJECT, OPERACAO, CHAVE, PAYLOAD_HASH, RESPOSTA_STATUS, RESPOSTA_JSON) VALUES ('fixture-citizen-a', 'CREATE_PREPARATION', 'base-test', RPAD('a', 64, 'a'), 201, '{"id":101}')]', -1, 'Chave duplicada');
    expect_error(q'[UPDATE PT_IDEMPOTENCIA SET RESPOSTA_JSON = 'nao-json' WHERE CHAVE = 'base-test']', -2290, 'JSON inválido');
    ROLLBACK TO idempotencia;

    SAVEPOINT rollback_item;
    UPDATE PT_ITEM_PREPARATIVO SET CONCLUIDO = 1 WHERE ID = 101;
    ROLLBACK TO rollback_item;
    SELECT CONCLUIDO INTO v_count FROM PT_ITEM_PREPARATIVO WHERE ID = 101;
    IF v_count <> 0 THEN
        RAISE_APPLICATION_ERROR(-20992, 'Rollback não restaurou o item');
    END IF;
    DBMS_OUTPUT.PUT_LINE('Base Oracle: contagens, constraints, idempotência e rollback OK.');
END;
