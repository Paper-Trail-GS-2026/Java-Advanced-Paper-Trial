    PROCEDURE assert_count(p_sql VARCHAR2, p_expected NUMBER, p_label VARCHAR2) IS
        v_actual NUMBER;
    BEGIN
        EXECUTE IMMEDIATE p_sql INTO v_actual;
        IF v_actual <> p_expected THEN
            RAISE_APPLICATION_ERROR(-20990, p_label || ': expected ' || p_expected || ', received ' || v_actual);
        END IF;
    END;

