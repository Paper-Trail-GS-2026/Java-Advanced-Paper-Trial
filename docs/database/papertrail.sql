PROMPT 02. Catalog and identity schema (Java)

CREATE TABLE PT_USER (
    ID NUMBER(18) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    NAME VARCHAR2(120 CHAR) NOT NULL,
    EMAIL VARCHAR2(254 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
    ROLE_NAME VARCHAR2(10 CHAR) DEFAULT 'CITIZEN' NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PT_USER PRIMARY KEY (ID),
    CONSTRAINT UQ_PT_USER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_PT_USER_ID CHECK (ID > 0),
    CONSTRAINT CK_PT_USER_NAME CHECK (TRIM(NAME) IS NOT NULL),
    CONSTRAINT CK_PT_USER_EMAIL CHECK (TRIM(EMAIL) IS NOT NULL AND EMAIL = LOWER(TRIM(EMAIL))),
    CONSTRAINT CK_PT_USER_ROLE CHECK (ROLE_NAME IN ('CITIZEN', 'MANAGER'))
